import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test.beforeEach(async ({ page }) => {
  await page.route('**/api/**', route => route.fulfill({ status: 404, contentType: 'text/plain', body: 'Static demo' }));
  await page.goto('/'); await expect(page.getByRole('heading', { name: 'Conecta tus datos.' })).toBeVisible();
});
async function addProfile(page, name = 'Mi Event Log', environment = 'IST') {
  await page.locator('[data-action="connect"]').last().click();
  await page.locator('#conn-name').fill(name);
  await page.locator('#conn-environment').selectOption(environment);
  await expect(page.locator('#conn-uri')).toHaveAttribute('readonly');
  await page.locator('#connect-submit').click();
  await expect(page.locator('.document-card').first()).toBeVisible();
}
