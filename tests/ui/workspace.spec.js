test('insert, inspect, edit, delete, invalid JSON and projection protection', async ({ page }) => {
  await addProfile(page);
  await page.locator('[data-action="insert"]').click();
  await page.locator('#document-editor').fill(JSON.stringify({ marker: 'ui-crud', status: 'SUCCESS', created_at: { $date: '2026-11-13T12:00:00Z' } }, null, 2));
  await page.locator('#write-submit').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('#query-filter').fill('{ "marker": "ui-crud" }');
  await page.locator('[data-action="run"]').click();
  await expect(page.locator('.document-card')).toHaveCount(1);
  await page.locator('[data-action="edit"]').click();
  const doc = JSON.parse(await page.locator('#document-editor').inputValue());
  doc.status = 'EDITED';
  await page.locator('#document-editor').fill(JSON.stringify(doc, null, 2));
  await page.locator('#write-submit').click();
  await expect(page.locator('.document-status')).toHaveText('EDITED');
  await page.locator('[data-action="delete"]').click();
  await expect(page.getByRole('dialog')).toContainText('Esta acción no se puede deshacer');
  await page.locator('#delete-submit').click();
  await expect(page.locator('.document-card')).toHaveCount(0);
  await page.locator('#query-filter').fill('{'); await page.locator('[data-action="run"]').click();
  await expect(page.getByRole('alert').first()).toContainText('JSON inválido');
  await page.locator('[data-action="reset"]').click();
  await page.locator('[data-action="advanced"]').click();
  await page.locator('#query-projection').fill('{ "status": 1 }'); await page.locator('[data-action="run"]').click();
  await expect(page.locator('[data-action="edit"]').first()).toBeDisabled();
  await expect(page.locator('.projection-notice')).toBeVisible();
});
test('empty start, named profiles, disconnect, reload, reconnect, edit and explicit removal', async ({ page }) => {
  await expect(page.locator('.connection-item')).toHaveCount(0);
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/scotia-compass-empty.png', animations: 'disabled' });
  await addProfile(page);
  await expect(page.locator('.connection-item')).toHaveCount(1);
  await expect(page.locator('.connection-item')).toContainText('Mi Event Log');
  await page.locator('[data-action="disconnect-profile"]').click();
  await expect(page.locator('.connection-item')).toHaveCount(1);
  await expect(page.locator('.disconnected-workspace')).toContainText('Tu configuración está guardada');
  await expect(page.locator('.document-card')).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.connection-item')).toHaveCount(1);
  await expect(page.locator('.profile-status')).toHaveText('Desconectada');
  await page.locator('[data-action="reconnect-profile"]').click();
  await expect(page.locator('.document-card')).toHaveCount(20);
  await page.locator('[data-action="profile-details"]').click();
  await page.locator('[data-action="edit-profile"]').click();
  await page.locator('#conn-name').fill('Atlas de integración');
  await page.locator('#conn-color').selectOption('violet');
  await page.locator('#connect-submit').click();
  await expect(page.locator('.connection-item')).toHaveCount(1);
  await expect(page.locator('.connection-item')).toContainText('Atlas de integración');
  await expect(page.locator('.connection-icon')).toHaveClass(/profile-violet/);
  await page.locator('[data-action="profile-details"]').click();
  await page.locator('[data-action="remove-profile"]').click();
  await page.locator('#remove-profile-submit').click();
  await page.reload();
  await expect(page.locator('.connection-item')).toHaveCount(0);
});
